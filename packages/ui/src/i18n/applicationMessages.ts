/** 必须在参数插值前调用，不能重写用户内容或运行时返回的品牌名称。 */
export function resolveApplicationMessage(
  locale: Locale,
  id: string,
  message: string,
  managedEdition = ZHILIU_DESKTOP_ENABLED,
): string {
  if (!managedEdition || !APPLICATION_MESSAGE_IDS.has(id)) {
    return message;
  }
  if (locale === "zh-CN" && id === "welcome.title") {
    return "欢迎使用织流";
  }
  return message.replaceAll("ZCode", locale === "zh-CN" ? "织流" : "Zhiliu");
}
